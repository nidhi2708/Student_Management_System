-- ==========================================
-- FUNCTION : CALCULATE_GRADE
-- ==========================================

CREATE OR REPLACE FUNCTION CALCULATE_GRADE(
P_MARKS NUMBER
)
RETURN VARCHAR2
IS
BEGIN
IF P_MARKS >= 90 THEN
RETURN 'A';
ELSIF P_MARKS >= 80 THEN
RETURN 'B';
ELSIF P_MARKS >= 70 THEN
RETURN 'C';
ELSE
RETURN 'D';
END IF;
END;
