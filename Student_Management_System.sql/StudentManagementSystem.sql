-- ==========================================
-- REPORT QUERY
-- ==========================================

SELECT
S.STUDENT_NAME,
C.COURSE_NAME,
M.MARKS,
A.ATTENDANCE_PERCENT
FROM STUDENT S
JOIN MARKS M
ON S.STUDENT_ID = M.STUDENT_ID
JOIN COURSE C
ON M.COURSE_ID = C.COURSE_ID
JOIN ATTENDANCE A
ON S.STUDENT_ID = A.STUDENT_ID
AND C.COURSE_ID = A.COURSE_ID;
