-- ==========================================
-- CURSOR PROCEDURE
-- ==========================================

CREATE OR REPLACE PROCEDURE DISPLAY_STUDENTS
AS
CURSOR STUD_CURSOR IS
SELECT STUDENT_ID,
STUDENT_NAME
FROM STUDENT;

```
V_ID STUDENT.STUDENT_ID%TYPE;
V_NAME STUDENT.STUDENT_NAME%TYPE;
```

BEGIN

```
OPEN STUD_CURSOR;

LOOP
    FETCH STUD_CURSOR
    INTO V_ID, V_NAME;

    EXIT WHEN STUD_CURSOR%NOTFOUND;

    DBMS_OUTPUT.PUT_LINE(
        V_ID || ' - ' || V_NAME
    );

END LOOP;

CLOSE STUD_CURSOR;
```

END;
