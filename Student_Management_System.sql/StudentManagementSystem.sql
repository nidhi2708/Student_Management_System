-- ==========================================
-- TRIGGER : CHECK_MARKS
-- ==========================================

CREATE OR REPLACE TRIGGER CHECK_MARKS
BEFORE INSERT OR UPDATE
ON MARKS
FOR EACH ROW
BEGIN
IF :NEW.MARKS < 0 THEN
RAISE_APPLICATION_ERROR(
-20001,
'Marks cannot be negative'
);
END IF;
END;
